def copy_project_seed_files() -> None:
    """Refresh local RTL, SDC, and ROM MIF inputs in the generated CLI project."""
    required_seed_files = (
        seed_rtl_dir / "filelist.f",
        seed_rtl_dir / "hololink.f",
        seed_sdc_file,
        seed_rom_mif,
    )
    missing_seed_files = [path for path in required_seed_files if not path.is_file()]
    if missing_seed_files:
        raise FileNotFoundError(
            "Missing project seed file(s): " + ", ".join(str(path) for path in missing_seed_files)
        )

    # Copy only seed assets. Existing IP content in output_dir/ip is untouched.
    shutil.copytree(seed_rtl_dir, rtl_dir, dirs_exist_ok=True)
    generate_efinix_apb_reg_overlay()
    stage_hololink_file()
    shutil.copy2(seed_sdc_file, sdc_file)
    # Synthesis resolves ROM_MIF ("efx_rom_mif.mem") from the project root.
    shutil.copy2(seed_rom_mif, rom_mif_file)


def generate_efinix_apb_reg_overlay() -> None:
    """Generate Efinity's register-based s_apb_reg implementation from shared RTL."""
    if not shared_apb_reg.is_file():
        raise FileNotFoundError(f"Shared APB register RTL not found: {shared_apb_reg}")

    source = shared_apb_reg.read_text()
    distributed_memory = (
        '(* ram_style = "distributed" *) logic [31:0] lut_mem [N_CTRL]'
        '/*synthesis syn_ramstyle = "distributed"*/;'
    )
    registered_memory = (
        '(* syn_ramstyle = "registers" *) logic [31:0] lut_mem [N_CTRL];'
    )
    conditional_read = """    if (reg_rden) begin
      w_rdata     <= lut_mem[reg_addr];
    end"""
    unconditional_read = "    w_rdata <= lut_mem[reg_addr];"

    if source.count(distributed_memory) != 1 or source.count(conditional_read) != 1:
        raise RuntimeError(
            f"Unexpected s_apb_reg implementation in {shared_apb_reg}; "
            "update the Efinity compatibility overlay generator."
        )

    overlay = source.replace(distributed_memory, registered_memory).replace(
        conditional_read, unconditional_read
    )
    efinix_apb_reg.write_text(
        "// Generated by build_interface.py; do not edit.\n"
        "// Efinity cannot infer the shared s_apb_reg dual-port RAM pattern.\n"
        + overlay
    )


def stage_hololink_file() -> None:
    """Normalize shared nv_hsb_ip paths for the generated project file list."""
    if not shared_ip_dir.is_dir():
        raise FileNotFoundError(f"Shared Hololink RTL directory not found: {shared_ip_dir}")

    staged_filelist = rtl_dir / "hololink.f"
    relative_ip_dir = os.path.relpath(shared_ip_dir, rtl_dir).replace(os.sep, "/")
    path_pattern = re.compile(r"(?:\.\./)+nv_hsb_ip")
    staged_contents = path_pattern.sub(relative_ip_dir, staged_filelist.read_text())
    shared_apb_reg_entry = f"{relative_ip_dir}/lib_apb/s_apb_reg.sv"
    if staged_contents.count(shared_apb_reg_entry) != 1:
        raise RuntimeError(
            f"Expected one shared s_apb_reg entry in {staged_filelist}, "
            f"found {staged_contents.count(shared_apb_reg_entry)}."
        )
    staged_contents = staged_contents.replace(shared_apb_reg_entry, efinix_apb_reg.name)
    staged_filelist.write_text(staged_contents)

    missing_sources = []
    for line in staged_contents.splitlines():
        source = line.strip()
        if not source or source.startswith("//") or source.startswith("+"):
            continue
        if "nv_hsb_ip/" not in source:
            continue
        if not (rtl_dir / source).is_file():
            missing_sources.append(source)
    if missing_sources:
        raise FileNotFoundError(
            "Staged Hololink source file(s) not found: " + ", ".join(missing_sources)
        )


def add_rtl_design_sources(project_path: Path) -> None:
    """Register the CLI project's local RTL file lists after Efinity saves."""
    namespace = {"efx": "http://www.efinixinc.com/enf_proj"}
    ET.register_namespace("efx", namespace["efx"])

    tree = ET.parse(project_path)
    design_info = tree.getroot().find("efx:design_info", namespace)
    if design_info is None:
        raise ValueError(f"Invalid Efinity project: missing design_info in {project_path}")

    top_module_node = design_info.find("efx:top_module", namespace)
    if top_module_node is None:
        raise ValueError(f"Invalid Efinity project: missing top_module in {project_path}")
    top_module_node.set("name", top_module)

    design_file_tag = f"{{{namespace['efx']}}}design_file"

    for design_file in design_info.findall("efx:design_file", namespace):
        design_info.remove(design_file)

    # Keep the source list directly after <efx:top_module>, as Efinity does.
    insert_at = 1
    for filelist in rtl_filelists:
        design_info.insert(
            insert_at,
            ET.Element(
                design_file_tag,
                {
                    "name": f"rtl/{filelist.name}",
                    "version": "na",
                    "library": "default",
                },
            ),
        )
        insert_at += 1

    tree.write(project_path, encoding="UTF-8", xml_declaration=True)


def add_sdc_constraint(project_path: Path) -> None:
    """Register the CLI project's local timing constraint file."""
    namespace = {"efx": "http://www.efinixinc.com/enf_proj"}
    ET.register_namespace("efx", namespace["efx"])

    tree = ET.parse(project_path)
    constraint_info = tree.getroot().find("efx:constraint_info", namespace)
    if constraint_info is None:
        raise ValueError(f"Invalid Efinity project: missing constraint_info in {project_path}")

    for existing_sdc in constraint_info.findall("efx:sdc_file", namespace):
        constraint_info.remove(existing_sdc)

    sdc_tag = f"{{{namespace['efx']}}}sdc_file"
    constraint_info.insert(0, ET.Element(sdc_tag, {"name": sdc_file.name}))
    tree.write(project_path, encoding="UTF-8", xml_declaration=True)




def apply_n1156_hsb_peri_settings(peri_file: Path) -> None:
    """Apply N1156_HSB settings that Efinity's public API cannot express."""
    namespace = {"efxpt": "http://www.efinixinc.com/peri_design_db"}
    ET.register_namespace("efxpt", namespace["efxpt"])
    tree = ET.parse(peri_file)
    root = tree.getroot()
    root.set("db_version", "20261009")

    gpio_info = root.find("efxpt:gpio_info", namespace)
    if gpio_info is None:
        raise ValueError(f"Invalid periphery file: missing gpio_info in {peri_file}")

    buses = gpio_info.findall("efxpt:bus", namespace)
    for bus in buses:
        gpio_info.remove(bus)
    for bus_name in ("led", "SFP_TXDISABLE"):
        bus = next((bus for bus in buses if bus.get("name") == bus_name), None)
        if bus is None:
            raise ValueError(f"Invalid periphery file: missing {bus_name} GPIO bus")
        gpio_info.append(bus)

    for gpio in root.findall(".//efxpt:comp_gpio", namespace):
        if gpio.get("name", "").startswith("SFP_TXDISABLE["):
            output_config = gpio.find("efxpt:output_config", namespace)
            if output_config is None:
                raise ValueError(f"Invalid periphery file: missing output config for {gpio.get('name')}")
            output_config.set("tied_option", "__gnd__")

    pll = root.find(".//efxpt:pll[@name='pll_inst1']", namespace)
    if pll is None:
        raise ValueError("Invalid periphery file: missing pll_inst1")

    adv_prop = pll.find("efxpt:adv_prop", namespace)
    clk_100m = pll.find("efxpt:comp_output_clock[@name='clk_100m']", namespace)
    if adv_prop is None or clk_100m is None:
        raise ValueError("Invalid periphery file: incomplete pll_inst1 configuration")

    adv_prop.set("feedback_mode", "core")
    pll_params = {
        "HALF_DC_SHIFT_EN": "true",
        "PDIV": "13",
        "SWALLOWING_DIV": "14",
    }
    for param in clk_100m.findall(".//efxpt:param", namespace):
        if param.get("name") in pll_params:
            param.set("value", pll_params[param.get("name")])

    osc = root.find(".//efxpt:osc[@name='osc_inst1']", namespace)
    clock_lane = root.find(".//efxpt:mipi[@name='dphy_rx1']/efxpt:mipi_hard_dphy_rx_info/"
                           "efxpt:clock_lane", namespace)
    if osc is None or clock_lane is None:
        raise ValueError("Invalid periphery file: incomplete oscillator or MIPI configuration")

    osc.set("frequency", "DIV1")
    clock_lane.set("lane_id", "2")

    quad = root.find(".//efxpt:quad_lane[@name='cmn_inst1']", namespace)
    if quad is None:
        raise ValueError("Invalid periphery file: missing cmn_inst1")

    quad_params = {
        "PMA_CMN__cmn_plllc_clk0_preg__cmn_plllc_clk0outdiv_mode0_preg": "0x2",
        "PMA_CMN__cmn_plllc_fbdiv_int_mode0_preg__cmn_plllc_fbdivint_mode0_preg": "0x21",
    }
    for param in quad.findall(".//efxpt:param", namespace):
        if param.get("name") in quad_params:
            param.set("value", quad_params[param.get("name")])
    for pin_type in ("PHY_CMN_RESET_N", "DTB_DATA"):
        pin = quad.find(f".//efxpt:pin[@type_name='{pin_type}']", namespace)
        if pin is None:
            raise ValueError(f"Invalid periphery file: missing {pin_type} pin")
        pin.set("name", "")

    lane = root.find(".//efxpt:lane_10g[@name='sfp0']", namespace)
    if lane is None:
        raise ValueError("Invalid periphery file: missing sfp0")

    usx_an_enable = lane.find(
        ".//efxpt:param[@name='10G_PCS_L_NID__control_register__usx_an_enable']",
        namespace,
    )
    if usx_an_enable is None:
        raise ValueError("Invalid periphery file: missing sfp0 USX AN setting")
    usx_an_enable.set("value", "false")

    tree.write(peri_file, encoding="UTF-8", xml_declaration=True)


